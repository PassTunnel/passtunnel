// macOS only, like the helper's file checks (F_GETPATH) it uses.
#if os(macOS)
import XCTest

@testable import PassTunnelShared
@testable import PassTunnelVPNConfig

/// `HelperCore.prepareOpenConnect` against a temporary home and run root, with injected uids and
/// versions; it never stages or runs a tool (the hook path is given), and nothing runs as root.
final class OpenConnectSessionTests: XCTestCase {
    var base: URL!
    var home: URL!
    var profiles: URL!
    var runRoot: URL!
    let me = getuid()
    let cookie = OpenConnectRequestTests.cookie

    override func setUpWithError() throws {
        var template = Array("/tmp/pt-oc-XXXXXX".utf8CString)
        guard let made = mkdtemp(&template) else { throw XCTSkip("mkdtemp failed") }
        base = URL(fileURLWithPath: String(cString: made))
        home = base.appendingPathComponent("home")
        profiles = home.appendingPathComponent(PT.profilesSubpath)
        runRoot = base.appendingPathComponent("run")
        try FileManager.default.createDirectory(at: profiles.appendingPathComponent("acme"), withIntermediateDirectories: true)
        try FileManager.default.createDirectory(at: runRoot, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
    }

    override func tearDownWithError() throws {
        try? FileManager.default.removeItem(at: base)
    }

    func core(macOS: (Int, Int)? = (26, 0)) -> HelperCore {
        let homePath = home.path, me = self.me
        var core = HelperCore(
            runRoot: runRoot.path, homeDirectory: { $0 == me ? homePath : nil }, userName: { $0 == me ? "alice" : nil })
        core.systemVersion = macOS.map { OperatingSystemVersion(majorVersion: $0.0, minorVersion: $0.1, patchVersion: 0) }
        return core
    }

    var acmeDir: String { profiles.appendingPathComponent("acme").path }
    var runDir: String { PT.sessionDir(uid: me, profileID: "acme", runRoot: runRoot.path) }
    var logPath: String { acmeDir + "/vpn.log" }

    func start(_ change: (inout OpenConnectStart) -> Void = { _ in }) -> OpenConnectStart {
        OpenConnectRequestTests.start {
            $0.profileDir = self.acmeDir
            $0.logPath = self.logPath
            change(&$0)
        }
    }

    /// Records whether the tools were staged (the hook path asked for).
    final class Stager {
        var calls = 0
        var path = exampleHook
        var failure: Error?
        func hookPath() throws -> String {
            calls += 1
            if let failure { throw failure }
            return path
        }
    }

    func exists(_ path: String) -> Bool {
        var st = stat()
        return lstat(path, &st) == 0
    }

    func attributes(_ path: String) throws -> (mode: Int, owner: uid_t) {
        let a = try FileManager.default.attributesOfItem(atPath: path)
        return ((a[.posixPermissions] as! NSNumber).intValue, (a[.ownerAccountID] as! NSNumber).uint32Value)
    }

    func testPrepareWritesTheConfigPolicyAndLog() throws {
        let stager = Stager()
        let plan = try core().prepareOpenConnect(start(), uid: me, hookPath: stager.hookPath)
        defer { close(plan.logFD) }
        XCTAssertEqual(stager.calls, 1)
        XCTAssertEqual(plan.tool, .openconnect)
        XCTAssertEqual(plan.profileID, "acme")
        XCTAssertEqual(plan.ownerUID, me)
        XCTAssertEqual(plan.runDir, runDir)
        XCTAssertEqual(plan.sessionDir.path, runDir)
        XCTAssertNil(plan.mgmtSocket)
        XCTAssertNil(plan.dnsUpdownPath)
        XCTAssertEqual(plan.arguments, ["--config=" + runDir + "/openconnect.conf"])

        XCTAssertEqual(
            try String(contentsOfFile: runDir + "/openconnect.conf", encoding: .utf8),
            """
            # Generated by PassTunnel. Do not edit.
            protocol anyconnect
            server https://vpn.example.com:8443/
            cookie \(cookie)
            servercert \(examplePin)
            resolve vpn.example.com:192.0.2.10
            script \(exampleHook)
            non-inter
            reconnect-timeout 60

            """)
        XCTAssertEqual(try String(contentsOfFile: runDir + "/policy", encoding: .utf8), "uid=\(me)\nprofile=acme\nset_routes=1\nset_dns=1\n")
        // Owned by the helper (root when it runs; here the test's user), readable by nobody else.
        for (path, mode) in [(runDir, 0o711), (runDir + "/openconnect.conf", 0o600), (runDir + "/policy", 0o600), (logPath, 0o600)] {
            let a = try attributes(path)
            XCTAssertEqual(a.mode, mode, path)
            XCTAssertEqual(a.owner, geteuid(), path)
        }
        XCTAssertEqual(Set(try FileManager.default.contentsOfDirectory(atPath: runDir)), ["openconnect.conf", "policy"])
        // The log is a fresh, empty file the tool appends to.
        XCTAssertEqual(try Data(contentsOf: URL(fileURLWithPath: logPath)).count, 0)

        // Stopping or a finished tool removes the run directory, and the cookie with it.
        core().removeRunDir(profileID: "acme", uid: me)
        XCTAssertFalse(exists(runDir))
    }

    func testVariants() throws {
        let v6 = try core().prepareOpenConnect(
            start {
                $0.host = "2001:db8::1"; $0.port = 443; $0.connectURL = "https://[2001:db8::1]/"; $0.resolve = nil
                $0.tlsOnly = true; $0.setDNS = false; $0.setRoutes = false; $0.profileServerCert = ""
            }, uid: me, hookPath: Stager().hookPath)
        defer { close(v6.logFD) }
        let text = try String(contentsOfFile: runDir + "/openconnect.conf", encoding: .utf8)
        XCTAssertTrue(text.contains("\nserver https://[2001:db8::1]/\n"))
        XCTAssertFalse(text.contains("resolve"))
        XCTAssertTrue(text.hasSuffix("\nreconnect-timeout 60\nno-dtls\n"))
        XCTAssertEqual(try String(contentsOfFile: runDir + "/policy", encoding: .utf8), "uid=\(me)\nprofile=acme\nset_routes=0\nset_dns=0\n")
    }

    func testStaleSessionDirectoryIsReplaced() throws {
        try FileManager.default.createDirectory(atPath: runDir, withIntermediateDirectories: true)
        try Data("stale".utf8).write(to: URL(fileURLWithPath: runDir + "/openconnect.conf"))
        let plan = try core().prepareOpenConnect(start(), uid: me, hookPath: Stager().hookPath)
        defer { close(plan.logFD) }
        XCTAssertTrue(try String(contentsOfFile: runDir + "/openconnect.conf", encoding: .utf8).contains("cookie \(cookie)\n"))
    }

    /// Below macOS 15.4 nothing is read, staged or written, whatever the request.
    func testOlderMacOSIsRefusedBeforeAnything() throws {
        for request in [start(), start { $0.cookie = "" }, start { $0.profileDir = "/etc" }] {
            let stager = Stager()
            XCTAssertThrowsError(try core(macOS: (15, 3)).prepareOpenConnect(request, uid: me, hookPath: stager.hookPath)) {
                XCTAssertEqual($0 as? HelperCore.Failure, .requiresNewerMacOS("Cisco AnyConnect", "15.4"))
            }
            XCTAssertEqual(stager.calls, 0, "nothing staged")
            XCTAssertFalse(exists(runRoot.path + "/\(me)"), "no session directory")
            XCTAssertFalse(exists(logPath), "no log")
        }
        let plan = try core(macOS: (15, 4)).prepareOpenConnect(start(), uid: me, hookPath: Stager().hookPath)
        close(plan.logFD)
        let linux = try core(macOS: nil).prepareOpenConnect(start(), uid: me, hookPath: Stager().hookPath)
        close(linux.logFD)
    }

    // MARK: Palo Alto GlobalProtect (protocol 5)

    func gpStart(_ change: (inout OpenConnectStart) -> Void = { _ in }) -> OpenConnectStart {
        GlobalProtectRequestTests.start {
            $0.profileDir = self.acmeDir
            $0.logPath = self.logPath
            change(&$0)
        }
    }

    /// The root file for the gateway the sign-in ended on, the cookie as printed, the gateway's key; the masker
    /// gets GlobalProtect's secrets.
    func testPrepareGlobalProtect() throws {
        let stager = Stager()
        let plan = try core().prepareOpenConnect(gpStart(), uid: me, hookPath: stager.hookPath)
        defer { close(plan.logFD) }
        XCTAssertEqual(stager.calls, 1)
        XCTAssertEqual(plan.tool, .openconnect)
        XCTAssertEqual(plan.arguments, ["--config=" + runDir + "/openconnect.conf"])
        XCTAssertEqual(plan.maskedSecrets, [exampleGPCookie, exampleGPAuthcookie])
        XCTAssertEqual(
            try String(contentsOfFile: runDir + "/openconnect.conf", encoding: .utf8),
            """
            # Generated by PassTunnel. Do not edit.
            protocol gp
            server https://gw1.example.com/
            cookie \(exampleGPCookie)
            servercert \(otherExamplePin)
            resolve gw1.example.com:192.0.2.20
            script \(exampleHook)
            non-inter
            reconnect-timeout 60

            """)
        XCTAssertEqual(try String(contentsOfFile: runDir + "/policy", encoding: .utf8), "uid=\(me)\nprofile=acme\nset_routes=1\nset_dns=1\n")
        for (path, mode) in [(runDir + "/openconnect.conf", 0o600), (runDir + "/policy", 0o600), (logPath, 0o600)] {
            XCTAssertEqual(try attributes(path).mode, mode, path)
        }
        core().removeRunDir(profileID: "acme", uid: me)

        // TLS only (no ESP) and an IP-literal gateway; `disable-ipv6` when the daemon decides it (Linux before 9.20).
        var linux = core(macOS: nil)
        linux.openConnectDisableIPv6 = true
        let v4 = try linux.prepareOpenConnect(
            gpStart {
                $0.host = "192.0.2.20"; $0.port = 4443; $0.connectURL = "https://192.0.2.20:4443/"; $0.resolve = nil; $0.tlsOnly = true
            }, uid: me, hookPath: Stager().hookPath)
        defer { close(v4.logFD) }
        let text = try String(contentsOfFile: runDir + "/openconnect.conf", encoding: .utf8)
        XCTAssertTrue(text.contains("\nserver https://192.0.2.20:4443/\n"))
        XCTAssertFalse(text.contains("resolve"))
        XCTAssertTrue(text.hasSuffix("\nreconnect-timeout 60\nno-dtls\ndisable-ipv6\n"), text)
    }

    /// The daemon's `disable-ipv6` never reaches a Cisco AnyConnect file.
    func testDisableIPv6IsForGlobalProtectOnly() throws {
        var linux = core(macOS: nil)
        linux.openConnectDisableIPv6 = true
        let plan = try linux.prepareOpenConnect(start(), uid: me, hookPath: Stager().hookPath)
        defer { close(plan.logFD) }
        XCTAssertFalse(try String(contentsOfFile: runDir + "/openconnect.conf", encoding: .utf8).contains("disable-ipv6"))
        XCTAssertEqual(plan.maskedSecrets, OpenConnectCookie.secrets(cookie))
    }

    /// Below macOS 15.4 the message names GlobalProtect, and nothing is read, staged or written.
    func testOlderMacOSIsRefusedForGlobalProtect() {
        for request in [gpStart(), gpStart { $0.cookie = "" }, gpStart { $0.profileDir = "/etc" }] {
            let stager = Stager()
            XCTAssertThrowsError(try core(macOS: (15, 3)).prepareOpenConnect(request, uid: me, hookPath: stager.hookPath)) {
                XCTAssertEqual($0 as? HelperCore.Failure, .requiresNewerMacOS("Palo Alto GlobalProtect", "15.4"))
                XCTAssertEqual(String(describing: $0), "Palo Alto GlobalProtect requires macOS 15.4 or later.")
            }
            XCTAssertEqual(stager.calls, 0, "nothing staged")
            XCTAssertFalse(exists(runRoot.path + "/\(me)"), "no session directory")
            XCTAssertFalse(exists(logPath), "no log")
        }
    }

    /// Invalid GlobalProtect requests, and starts that mix the two protocols, are refused before the tools are
    /// staged or anything is written, and no error carries the cookie.
    func testInvalidGlobalProtectRequestsTouchNothing() {
        let requests: [(String, OpenConnectStart)] = [
            ("Cisco AnyConnect cookie", gpStart { $0.cookie = self.cookie }),
            ("cookie line", gpStart { $0.cookie = exampleGPCookie + "\nscript /tmp/x" }),
            ("user group", gpStart { $0.usergroup = "gateway" }),
            ("key neither pin", gpStart { $0.serverCert = GlobalProtectRequestTests.thirdPin }),
            ("gateway pin", gpStart { $0.profileGatewayServerCert = "pin-sha256:abc" }),
            ("other server", gpStart { $0.connectURL = "https://vpn.example.com/" }),
            ("no resolve", gpStart { $0.resolve = nil }),
            ("profile directory", gpStart { $0.profileDir = "/etc" }),
            ("labelled Cisco AnyConnect", gpStart { $0.protocol = .anyconnect }),
            ("Cisco AnyConnect with a gateway pin", start { $0.profileGatewayServerCert = otherExamplePin }),
            ("Cisco AnyConnect with GlobalProtect's cookie", start { $0.cookie = exampleGPCookie })
        ]
        for (name, request) in requests {
            let stager = Stager()
            XCTAssertThrowsError(try core().prepareOpenConnect(request, uid: me, hookPath: stager.hookPath), name) {
                XCTAssertFalse(String(describing: $0).contains(exampleGPAuthcookie), name)
                XCTAssertFalse(String(describing: $0).contains(cookie), name)
            }
            XCTAssertEqual(stager.calls, 0, "\(name): nothing staged")
            XCTAssertFalse(exists(runRoot.path + "/\(me)"), "\(name): no session directory")
            XCTAssertFalse(exists(logPath), "\(name): no log")
        }
    }

    /// An invalid request (here: each kind of check) is refused before the tools are staged or anything
    /// is written, and its error never carries the cookie.
    func testInvalidRequestsTouchNothing() {
        let requests: [(String, OpenConnectStart)] = [
            ("cookie", start { $0.cookie = "abc\nscript /tmp/x" }),
            ("pin mismatch", start { $0.serverCert = otherExamplePin }),
            ("other server", start { $0.connectURL = "https://vpn.example.net:8443/" }),
            ("no resolve", start { $0.resolve = nil }),
            ("user group", start { $0.usergroup = "../x" }),
            ("profile ID", start { $0.profileID = "../acme" }),
            ("profile directory", start { $0.profileDir = "/etc" }),
            ("other profile's directory", start { $0.profileID = "other" }),
            ("log outside", start { $0.logPath = "/tmp/vpn.log" }),
            ("log name", start { $0.logPath = self.acmeDir + "/vpn.txt" })
        ]
        for (name, request) in requests {
            let stager = Stager()
            XCTAssertThrowsError(try core().prepareOpenConnect(request, uid: me, hookPath: stager.hookPath), name) {
                XCTAssertFalse(String(describing: $0).contains(cookie), name)
            }
            XCTAssertEqual(stager.calls, 0, "\(name): nothing staged")
            XCTAssertFalse(exists(runRoot.path + "/\(me)"), "\(name): no session directory")
            XCTAssertFalse(exists(logPath), "\(name): no log")
        }
    }

    func testStagingFailureAndBadHookPathWriteNothing() {
        struct StagingFailed: Error {}
        let failing = Stager()
        failing.failure = StagingFailed()
        XCTAssertThrowsError(try core().prepareOpenConnect(start(), uid: me, hookPath: failing.hookPath)) { XCTAssertTrue($0 is StagingFailed) }
        let bad = Stager()
        bad.path = "/tmp/hook; rm -rf /"
        XCTAssertThrowsError(try core().prepareOpenConnect(start(), uid: me, hookPath: bad.hookPath))
        XCTAssertFalse(exists(runRoot.path + "/\(me)"))
        XCTAssertFalse(exists(logPath))
    }

    /// A failure once the session directory exists (here the log cannot be created) removes it, and the
    /// cookie with it.
    func testFailureAfterTheConfigWasWrittenRemovesIt() throws {
        try FileManager.default.createDirectory(atPath: logPath, withIntermediateDirectories: false)
        try Data("x".utf8).write(to: URL(fileURLWithPath: logPath + "/keep"))
        XCTAssertThrowsError(try core().prepareOpenConnect(start(), uid: me, hookPath: Stager().hookPath)) {
            XCTAssertFalse(String(describing: $0).contains(cookie))
        }
        XCTAssertFalse(exists(runDir), "the config with the cookie is gone")
    }

    func testRunRootSymlinkIsRefused() throws {
        try FileManager.default.removeItem(at: runRoot)
        try FileManager.default.createSymbolicLink(atPath: runRoot.path, withDestinationPath: base.path)
        XCTAssertThrowsError(try core().prepareOpenConnect(start(), uid: me, hookPath: Stager().hookPath)) {
            XCTAssertEqual($0 as? HelperCore.Failure, .symlinkNotAllowed(runRoot.path))
        }
    }

    /// The session record the helper writes before the tool runs, read back as the hook and a restarted
    /// helper read it.
    func testSessionStateIsReadOnlyFromARegularFileWeOwn() throws {
        let dir = base.appendingPathComponent("s").path
        try FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
        let state = SessionState(pid: 4242, uid: me, executable: "/x/openconnect", profileDir: acmeDir, mgmtSocket: nil)
        try HelperCore.writeNewFile(dir + "/state", Data(try state.text().utf8), mode: 0o600)
        XCTAssertEqual(SessionState.read(dir + "/state"), state)
        XCTAssertEqual(symlink(dir + "/state", dir + "/link"), 0)
        XCTAssertNil(SessionState.read(dir + "/link"), "never through a link")
        XCTAssertEqual(link(dir + "/state", dir + "/hard"), 0)
        XCTAssertNil(SessionState.read(dir + "/state"), "never a hard-linked file")
        XCTAssertNil(SessionState.read(dir + "/missing"))
        XCTAssertNil(SessionState.read(dir), "not a directory")
    }
}
