// MARK: - Standard input of the sign-in

final class OpenConnectAnswersTests: XCTestCase {
    func testLayouts() throws {
        XCTAssertEqual(try OpenConnectAnswers.separate(password: "pass word", code: "123456"), Array("pass word\n123456\n".utf8))
        XCTAssertEqual(try OpenConnectAnswers.combined("pass word123456"), Array("pass word123456\n".utf8))
        XCTAssertEqual(try OpenConnectAnswers.stdin(["şifre", "1"]), Array("şifre\n1\n".utf8))
    }

    func testLimits() throws {
        XCTAssertEqual(try OpenConnectAnswers.combined(String(repeating: "p", count: 4095)).count, 4096)
        // Bytes, not characters: "ş" is two.
        XCTAssertNoThrow(try OpenConnectAnswers.combined(String(repeating: "ş", count: 2047) + "x"))
        let secret = "SECRET-PASSWORD"
        for bad in [
            String(repeating: "p", count: 4096), String(repeating: "ş", count: 2048), "", secret + "\n", secret + "\r", "\r" + secret,
            secret + "\u{0}x"
        ] as [String] {
            XCTAssertThrowsError(try OpenConnectAnswers.combined(bad), bad.debugDescription) {
                XCTAssertFalse("\($0)".contains(secret), "an error must not include the answer")
            }
            XCTAssertThrowsError(try OpenConnectAnswers.separate(password: "pw", code: bad), bad.debugDescription)
            XCTAssertThrowsError(try OpenConnectAnswers.separate(password: bad, code: "123456"), bad.debugDescription)
        }
        XCTAssertThrowsError(try OpenConnectAnswers.stdin([]))
    }
}
