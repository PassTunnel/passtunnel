        XCTAssertTrue(OpenConnectPin.isValid("pin-sha256:" + String(repeating: "A", count: 43) + "="))
        XCTAssertEqual(OpenConnectPin.length, examplePin.utf8.count)
    }

    func testNormalize() {
        XCTAssertEqual(OpenConnectPin.normalize(examplePin), examplePin)
        XCTAssertEqual(OpenConnectPin.normalize("  \(examplePin)\n"), examplePin)
        XCTAssertEqual(OpenConnectPin.normalize("PIN-SHA256:" + examplePin.dropFirst(11)), examplePin)
        XCTAssertFalse(OpenConnectPin.isValid("PIN-SHA256:" + examplePin.dropFirst(11)), "the stored form has the lowercase prefix")
        // base64 is case-sensitive (another case is another digest): only the prefix is lowercased.
        let mixed = "pin-sha256:" + String(repeating: "aB", count: 21) + "A="
        XCTAssertEqual(OpenConnectPin.normalize(mixed), mixed)
    }

    func testRefused() {
        let body = String(examplePin.dropFirst(11))
        let refused: [String] = [
            "", "pin-sha256:", body,
            String(examplePin.dropLast()),  // no '='
            String(examplePin.prefix(15)),  // a prefix: openconnect would match 4 characters or more
            String(examplePin.dropLast(2)) + "=",  // 42 characters
            examplePin + "=", examplePin + "A",
            "pin-sha256:" + body.replacingOccurrences(of: "+", with: "-"),  // base64url
            "pin-sha256:" + String(repeating: "A", count: 42) + "B=",  // not the encoding of a 32-byte digest
            "pin-sha256: " + body, "pin-sha256:" + String(body.dropLast()) + " =",
            "sha256:" + String(repeating: "ab", count: 32),
            "sha256:" + String(repeating: "AB", count: 32),
            "sha1:" + String(repeating: "ab", count: 20),
            String(repeating: "ab", count: 20),  // bare SHA-1 of the whole certificate
            String(repeating: "ab", count: 32),
            "pin-sha512:" + body,
            "pin-sha256:" + body + "\n"
        ]
        for s in refused {
            XCTAssertFalse(OpenConnectPin.isValid(s), s.debugDescription)
            if s != "pin-sha256:" + body + "\n" { XCTAssertNil(OpenConnectPin.normalize(s), s.debugDescription) }
        }
    }
