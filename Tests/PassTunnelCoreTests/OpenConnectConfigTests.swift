import XCTest

@testable import PassTunnelVPNConfig

/// Example pins: base64 SHA-256 of made-up bytes, not of any real server key.
let examplePin = "pin-sha256:z5GvjHUMCuD4zeB6PcpafVA6OZks+c8PGxSAuAx0Hgk="
let otherExamplePin = "pin-sha256:/+9qLXvY4QvSoKy/ojXS6HTlG1iniUJkmUyKWlahaLE="
/// Where the helper stages the hook (`<run root>/tools/<build>/Resources/bin/vpn-hook`, symlinks resolved).
let exampleHook = "/private/var/run/passtunnel/tools/0123abcd/Resources/bin/vpn-hook"

// MARK: - The root file

final class OpenConnectConfigTests: XCTestCase {
    let cookie = "webvpn=EXAMPLE-COOKIE-3F2A@1234@ABCD"

    func config(_ change: (inout OpenConnectConfig) -> Void = { _ in }) -> OpenConnectConfig {
        var c = OpenConnectConfig(
            host: "vpn.example.com", port: 8443, cookie: cookie, serverCert: examplePin, resolveAddress: "192.0.2.10",
            scriptPath: exampleHook)
        change(&c)
        return c
    }

    func testRender() throws {
        XCTAssertEqual(
            try config().render(),
            """
            # Generated by PassTunnel. Do not edit.
            protocol anyconnect
            server https://vpn.example.com:8443/
            cookie \(cookie)
            servercert \(examplePin)
            resolve vpn.example.com:192.0.2.10
            script \(exampleHook)
            non-inter
            reconnect-timeout 60

            """)
    }

    func testRenderVariants() throws {
        // Port 443 is left out, as openconnect prints CONNECT_URL; TLS only adds no-dtls at the end.
        let tls = try config {
            $0.port = 443; $0.tlsOnly = true
        }.render()
        XCTAssertTrue(tls.contains("\nserver https://vpn.example.com/\n"))
        XCTAssertTrue(tls.hasSuffix("\nreconnect-timeout 60\nno-dtls\n"))
        // The host is lowercased in both server and resolve, which openconnect compares byte for byte.
        let upper = try config { $0.host = "VPN.Example.COM" }.render()
        XCTAssertTrue(upper.contains("\nserver https://vpn.example.com:8443/\n"))
        XCTAssertTrue(upper.contains("\nresolve vpn.example.com:192.0.2.10\n"))
        // An IPv6 address to resolve to.
        XCTAssertTrue(try config { $0.resolveAddress = "2001:db8::10" }.render().contains("\nresolve vpn.example.com:2001:db8::10\n"))
        // An IP-literal host: no resolve; IPv6 in brackets.
        let v4 = try config {
            $0.host = "192.0.2.10"; $0.resolveAddress = nil
        }.render()
        XCTAssertTrue(v4.contains("\nserver https://192.0.2.10:8443/\n"))
        XCTAssertFalse(v4.contains("resolve"))
        let v6 = try config {
            $0.host = "2001:DB8::1"; $0.port = 443; $0.resolveAddress = nil
        }.render()
        XCTAssertTrue(v6.contains("\nserver https://[2001:db8::1]/\n"))
        XCTAssertFalse(v6.contains("resolve"))
    }

    func testResolveIsRequiredForAHostNameAndRefusedForAnAddress() {
        XCTAssertThrowsError(try config { $0.resolveAddress = nil }.render())
        XCTAssertThrowsError(try config { $0.host = "192.0.2.10" }.render())
        XCTAssertThrowsError(try config { $0.host = "2001:db8::1" }.render())
        for bad in ["", "vpn.example.com", "192.0.2", "192.0.2.10:443", "[2001:db8::1]", "fe80::1%en0", "2001:db8::1 ", "192.0.2.1\n"] {
            XCTAssertThrowsError(try config { $0.resolveAddress = bad }.render(), bad.debugDescription)
        }
    }

    func testFieldValidation() {
        XCTAssertThrowsError(try config { $0.port = 0 }.render()) {
            XCTAssertEqual($0 as? OpenConnectConfig.ValidationError, .invalidPort(0))
        }
        XCTAssertThrowsError(try config { $0.port = 65536 }.render())
        XCTAssertNoThrow(try config { $0.port = 65535 }.render())
        for bad in [
            "", "vpn.example.com:443", "vpn example.com", "-vpn.example.com", "https://vpn.example.com", "vpn.example.com/x",
            "fe80::1%en0", "vpn_example.com", String(repeating: "a", count: 254)
        ] as [String] {
            XCTAssertThrowsError(
                try config {
                    $0.host = bad; $0.resolveAddress = "192.0.2.10"
                }.render(), bad.debugDescription
            ) {
                XCTAssertEqual($0 as? OpenConnectConfig.ValidationError, .invalidHost)
            }
        }
        // The pin is required in the root file and must be full.
        for bad in ["", String(examplePin.dropLast()), "sha256:" + String(repeating: "ab", count: 32)] as [String] {
            XCTAssertThrowsError(try config { $0.serverCert = bad }.render()) {
                XCTAssertEqual($0 as? OpenConnectConfig.ValidationError, .invalidServerCert)
            }
        }
        for bad in [
            "", "vpn-hook", "bin/vpn-hook", "/a b", "/a;b", "/a$(x)", "/a`x`", "/a|b", "/a\\b", "/a//b", "/a/./b", "/a/../b",
            "/a/", "/a\u{0}b", "/" + String(repeating: "a", count: 1023)
        ] as [String] {
            XCTAssertThrowsError(try config { $0.scriptPath = bad }.render(), bad.debugDescription) {
                guard case .invalidValue("script", _)? = $0 as? OpenConnectConfig.ValidationError else { return XCTFail("\($0)") }
            }
        }
        XCTAssertNoThrow(try config { $0.scriptPath = "/" + String(repeating: "a", count: 1022) }.render())
    }

    /// The root run's `cookie` option: exactly the shapes `OpenConnectCookie.tunnelOption` gives.
    func testCookieRules() {
        XCTAssertNoThrow(try config { $0.cookie = "webvpn=" + String(repeating: "c", count: 4089) }.render())
        XCTAssertNoThrow(try config { $0.cookie = "webvpn=" + OpenConnectCookieTests.ocservToken }.render())
        XCTAssertNoThrow(try config { $0.cookie = OpenConnectCookieTests.strap }.render())
        for bad in [
            "", "webvpn=", "webvpn=" + String(repeating: "c", count: 4090), "EXAMPLE-COOKIE", OpenConnectCookieTests.ocservToken,
            "webvpn=AB12; extra=x", "extra=x; webvpn=AB12", "WEBVPN=AB12", " webvpn=AB12", "webvpn=AB12 ", "webvpn=a b", "webvpn=a;b",
            "webvpn=quote'd", "webvpn=a\"b", "webvpn=a,b", "webvpn=a\\b", "webvpn=tab\tx", "webvpn=x\ny", "webvpn=x\ry",
            "webvpn=x\u{0}y", "webvpn=x\u{7F}y", "webvpn=çerez", "openconnect_strapkey=; webvpn=AB12",
            "openconnect_strapkey=MHcC; webvpn=", "openconnect_strapkey=MHc; webvpn=AB12", "openconnect_strapkey=MH*C; webvpn=AB12",
            "openconnect_strapkey=MHcC;webvpn=AB12", "openconnect_strapkey=MHcC; webvpn=AB12; x=y"
        ] as [String] {
            XCTAssertThrowsError(try config { $0.cookie = bad }.render(), bad.debugDescription) { error in
                guard case .invalidValue("cookie", _)? = error as? OpenConnectConfig.ValidationError else { return XCTFail("\(error)") }
                if bad.count > 3 { XCTAssertFalse("\(error)".contains(bad), "the error must not include the cookie") }
            }
        }
    }

    func testInjectionRejectedInEveryField() {
        for p in ["x\nscript-tun", "x\rcsd-wrapper /tmp/x", "x\u{0}y", "x\u{2028}y", "x\u{85}y", "x\u{1b}[2J", "x\tno-cert-check"] {
            XCTAssertThrowsError(try config { $0.host = p }.render(), "host \(p.debugDescription)")
            XCTAssertThrowsError(try config { $0.cookie = p }.render(), "cookie \(p.debugDescription)")
            XCTAssertThrowsError(try config { $0.serverCert = examplePin + p }.render(), "pin \(p.debugDescription)")
            XCTAssertThrowsError(try config { $0.resolveAddress = "192.0.2.10" + p }.render(), "resolve \(p.debugDescription)")
            XCTAssertThrowsError(try config { $0.scriptPath = exampleHook + p }.render(), "script \(p.debugDescription)")
        }
    }

    func testDescriptionsNeverShowTheCookie() {
        let c = config()
        var dumped = ""
        dump(c, to: &dumped)
        for text in [c.description, c.debugDescription, String(describing: c), String(reflecting: c), "\(c)", dumped] {
            XCTAssertFalse(text.contains(cookie), text)
            XCTAssertTrue(text.contains("<redacted>"), text)
        }
        XCTAssertFalse(Mirror(reflecting: c).children.contains { "\($0.value)".contains(cookie) })
    }
}

// MARK: - The sign-in file

final class OpenConnectAuthConfigTests: XCTestCase {
    func config(_ change: (inout OpenConnectAuthConfig) -> Void = { _ in }) -> OpenConnectAuthConfig {
        var c = OpenConnectAuthConfig(host: "vpn.example.com", port: 8443, usergroup: "engineering", username: "alice")
        change(&c)
        return c
    }

    func testRenderWithTheSystemCABundle() throws {
        XCTAssertEqual(
            try config { $0.authgroup = "Remote Staff" }.render(noExternalAuth: true),
            """
            # Generated by PassTunnel. Do not edit.
            protocol anyconnect
            server https://vpn.example.com:8443/engineering
            user alice
            authgroup Remote Staff
            no-system-trust
            cafile /etc/ssl/cert.pem
            non-inter
            passwd-on-stdin
            no-external-auth

            """)
    }

    func testRenderWithAPin() throws {
        XCTAssertEqual(
            try config {
                $0.port = 443; $0.usergroup = ""; $0.serverCert = examplePin
            }.render(noExternalAuth: false),
            """
            # Generated by PassTunnel. Do not edit.
            protocol anyconnect
            server https://vpn.example.com/
            user alice
            servercert \(examplePin)
            non-inter
            passwd-on-stdin

            """)
    }

    /// Linux passes the distribution's CA bundle it checked; anything but a plain absolute path is refused.
    func testCAFile() throws {
        let linux = try config().render(caFile: "/etc/ssl/certs/ca-certificates.crt", noExternalAuth: false)
        XCTAssertTrue(linux.contains("\ncafile /etc/ssl/certs/ca-certificates.crt\n"))
        for bad in ["", "cert.pem", "/etc/ssl/my ca.pem", "/etc/ssl/cert.pem\nno-cert-check", "/etc/../tmp/ca.pem", "/etc/ssl/ca\u{0}.pem"] {
            XCTAssertThrowsError(try config().render(caFile: bad, noExternalAuth: true), bad.debugDescription) {
                guard case .invalidValue("CA file", _)? = $0 as? OpenConnectConfig.ValidationError else { return XCTFail("\($0)") }
            }
        }
    }

    func testHosts() throws {
        XCTAssertTrue(try config { $0.host = "2001:db8::1" }.render(noExternalAuth: true).contains("server https://[2001:db8::1]:8443/engineering\n"))
        XCTAssertTrue(
            try config {
                $0.host = "192.0.2.10"; $0.port = 443
            }.render(noExternalAuth: true).contains("server https://192.0.2.10/engineering\n"))
        XCTAssertThrowsError(try config { $0.host = "fe80::1%en0" }.render(noExternalAuth: true))
        XCTAssertThrowsError(try config { $0.port = 0 }.render(noExternalAuth: true))
    }

    func testUsergroup() throws {
        for good in ["engineering", "a", "eng/remote", "eng-1_2.x~y", String(repeating: "g", count: 255)] as [String] {
            XCTAssertNoThrow(try config { $0.usergroup = good }.render(noExternalAuth: true), good)
        }
        for bad in [
            "/engineering", "..", "eng/../x", "eng..x", "eng group", "eng?x=1", "eng#x", "eng%2f", "eng@x", "eng:x", "eng\\x", "eng\nx",
            "grüppe", String(repeating: "g", count: 256)
        ] as [String] {
            XCTAssertThrowsError(try config { $0.usergroup = bad }.render(noExternalAuth: true), bad.debugDescription) {
                guard case .invalidValue("user group", _)? = $0 as? OpenConnectConfig.ValidationError else { return XCTFail("\($0)") }
            }
        }
    }

    func testUserNameAndGroup() throws {
        // Free text, as long as openconnect reads it back unchanged.
        let text = try config {
            $0.username = "Ayşe Yılmaz # = x"; $0.authgroup = "Grup 1 = a"
        }.render(noExternalAuth: true)
        XCTAssertTrue(text.contains("\nuser Ayşe Yılmaz # = x\n"))
        XCTAssertTrue(text.contains("\nauthgroup Grup 1 = a\n"))
        XCTAssertNoThrow(try config { $0.username = String(repeating: "u", count: 255) }.render(noExternalAuth: true))
        for bad in [
            "", " alice", "alice ", "\talice", "=alice", "al\nice", "al\rice", "al\u{0}ice", "al\u{2028}ice", "al\u{85}ice",
            String(repeating: "u", count: 256)
        ] as [String] {
            XCTAssertThrowsError(try config { $0.username = bad }.render(noExternalAuth: true), bad.debugDescription) {
                guard case .invalidValue("user name", _)? = $0 as? OpenConnectConfig.ValidationError else { return XCTFail("\($0)") }
            }
            if !bad.isEmpty {
                XCTAssertThrowsError(try config { $0.authgroup = bad }.render(noExternalAuth: true), bad.debugDescription) {
                    guard case .invalidValue("group", _)? = $0 as? OpenConnectConfig.ValidationError else { return XCTFail("\($0)") }
                }
            }
        }
    }

    func testPinMustBeFull() {
        for bad in [String(examplePin.prefix(15)), "sha1:" + String(repeating: "ab", count: 20), String(repeating: "ab", count: 20)] as [String] {
            XCTAssertThrowsError(try config { $0.serverCert = bad }.render(noExternalAuth: true)) {
                XCTAssertEqual($0 as? OpenConnectConfig.ValidationError, .invalidServerCert)
            }
        }
    }
}

// MARK: - The final check of both files

final class OpenConnectRenderedCheckTests: XCTestCase {
    static let root = try! OpenConnectConfig(
        host: "vpn.example.com", port: 8443, cookie: "webvpn=EXAMPLE-COOKIE", serverCert: examplePin, resolveAddress: "192.0.2.10",
        scriptPath: exampleHook
    ).render()
    static let auth = try! OpenConnectAuthConfig(host: "vpn.example.com", usergroup: "eng", username: "alice", authgroup: "Staff")
        .render(noExternalAuth: true)
    static let pinnedAuth = try! OpenConnectAuthConfig(host: "vpn.example.com", username: "alice", serverCert: examplePin)
        .render(noExternalAuth: true)

    var root: String { Self.root }
    var auth: String { Self.auth }
    var pinnedAuth: String { Self.pinnedAuth }

    func lineCount(_ text: String) -> Int { text.split(separator: "\n", omittingEmptySubsequences: false).count - 1 }

    func assertRootUnsafe(_ text: String, lines: Int? = nil, file: StaticString = #filePath, line: UInt = #line) {
        XCTAssertThrowsError(
            try OpenConnectConfig.checkRendered(text, lineCount: lines ?? lineCount(text)), text.debugDescription, file: file, line: line
        ) {
            guard case .unsafeOutput? = $0 as? OpenConnectConfig.ValidationError else { return XCTFail("\($0)", file: file, line: line) }
        }
    }

    func assertAuthUnsafe(_ text: String, lines: Int? = nil, file: StaticString = #filePath, line: UInt = #line) {
        XCTAssertThrowsError(
            try OpenConnectAuthConfig.checkRendered(text, lineCount: lines ?? lineCount(text), caFile: OpenConnectConfig.systemCAFile),
            text.debugDescription, file: file, line: line
        ) {
            guard case .unsafeOutput? = $0 as? OpenConnectConfig.ValidationError else { return XCTFail("\($0)", file: file, line: line) }
        }
    }

    func testRenderedFilesPassTheCheck() throws {
        XCTAssertNoThrow(try OpenConnectConfig.checkRendered(root, lineCount: 9))
        XCTAssertNoThrow(try OpenConnectAuthConfig.checkRendered(auth, lineCount: 10, caFile: "/etc/ssl/cert.pem"))
        XCTAssertNoThrow(try OpenConnectAuthConfig.checkRendered(pinnedAuth, lineCount: 8, caFile: "/etc/ssl/cert.pem"))
        let keys = { (text: String) in text.split(separator: "\n").dropFirst().map { String($0.prefix { $0 != " " }) } }
        let fullRoot = try OpenConnectConfig(
            host: "vpn.example.com", cookie: "webvpn=c", serverCert: examplePin, resolveAddress: "192.0.2.1", scriptPath: "/x",
            tlsOnly: true
        ).render()
        XCTAssertEqual(keys(fullRoot), OpenConnectConfig.renderedKeys)
        XCTAssertEqual(keys(auth), OpenConnectAuthConfig.renderedKeys.filter { $0 != "servercert" })
    }

    func testTheCheckRefusesWhatAValidatorGapWouldLetThrough() {
        // Bytes openconnect would read differently, or not at all.
        assertRootUnsafe(root.replacingOccurrences(of: "EXAMPLE-COOKIE", with: "EXAMPLE\u{0}-COOKIE"))
        assertRootUnsafe(root.replacingOccurrences(of: "non-inter\n", with: "non-inter\r\n"))
        assertRootUnsafe(root.replacingOccurrences(of: "EXAMPLE-COOKIE", with: "EXAMPLE\u{1B}COOKIE"))
        assertRootUnsafe(root.replacingOccurrences(of: "EXAMPLE-COOKIE", with: "EXAMPLE\u{7F}COOKIE"))
        assertRootUnsafe(String(root.dropLast()))
        // Separators: only "key value" with one space.
        assertRootUnsafe(root.replacingOccurrences(of: "cookie webvpn", with: "cookie=webvpn"))
        assertRootUnsafe(root.replacingOccurrences(of: "cookie webvpn", with: "cookie\twebvpn"))
        assertRootUnsafe(root.replacingOccurrences(of: "cookie webvpn", with: "cookie  webvpn"))
        assertRootUnsafe(root.replacingOccurrences(of: "cookie webvpn", with: "cookie =webvpn"))
        // A bare value, which openconnect would split at its first '=' into another cookie.
        assertRootUnsafe(root.replacingOccurrences(of: "cookie webvpn=EXAMPLE-COOKIE", with: "cookie EXAMPLE-COOKIE"))
        assertRootUnsafe(root.replacingOccurrences(of: "cookie webvpn=EXAMPLE-COOKIE", with: "cookie EXAMPLE=COOKIE"))
        assertRootUnsafe(root.replacingOccurrences(of: "EXAMPLE-COOKIE", with: "EXAMPLE-COOKIE "))
        assertRootUnsafe(root.replacingOccurrences(of: "\ncookie", with: "\n cookie"))
        assertRootUnsafe(root.replacingOccurrences(of: "non-inter", with: "non-inter "))
        assertRootUnsafe(root.replacingOccurrences(of: "non-inter", with: "non-inter yes"))
        assertRootUnsafe(root.replacingOccurrences(of: "\nscript \(exampleHook)", with: "\nscript"))
        // Header, comments, empty lines, line count.
        assertRootUnsafe(root.replacingOccurrences(of: "# Generated by PassTunnel. Do not edit.\n", with: ""))
        assertRootUnsafe(root.replacingOccurrences(of: "non-inter\n", with: "non-inter\n# comment\n"))
        assertRootUnsafe(root.replacingOccurrences(of: "non-inter\n", with: "non-inter\n\n"))
        assertRootUnsafe(root, lines: 10)
        assertRootUnsafe(root, lines: 8)
        // Repeated, reordered, missing.
        assertRootUnsafe(root.replacingOccurrences(of: "non-inter\n", with: "non-inter\nnon-inter\n"))
        assertRootUnsafe(
            root.replacingOccurrences(of: "servercert \(examplePin)\n", with: "servercert \(examplePin)\nservercert \(otherExamplePin)\n"))
        assertRootUnsafe(
            root.replacingOccurrences(of: "protocol anyconnect\nserver", with: "server").replacingOccurrences(
                of: "8443/\n", with: "8443/\nprotocol anyconnect\n"))
        for required in ["protocol anyconnect\n", "servercert \(examplePin)\n", "script \(exampleHook)\n", "non-inter\n", "reconnect-timeout 60\n"] {
            assertRootUnsafe(root.replacingOccurrences(of: required, with: ""))
        }
        // Values render() never writes.
        assertRootUnsafe(root.replacingOccurrences(of: "protocol anyconnect", with: "protocol gp"))
        assertRootUnsafe(root.replacingOccurrences(of: "reconnect-timeout 60", with: "reconnect-timeout 300"))
        assertRootUnsafe(root.replacingOccurrences(of: examplePin, with: String(examplePin.prefix(20))))
        assertRootUnsafe(root.replacingOccurrences(of: exampleHook, with: "/opt/homebrew/etc/vpnc/vpnc-script;id"))
        assertRootUnsafe(root.replacingOccurrences(of: exampleHook, with: "/tmp/../x"))
        assertRootUnsafe(root.replacingOccurrences(of: "8443/\n", with: "8443/engineering\n"))
        assertRootUnsafe(root.replacingOccurrences(of: "https://", with: "http://"))
        assertRootUnsafe(root.replacingOccurrences(of: "resolve vpn.example.com:", with: "resolve other.example.com:"))
        assertRootUnsafe(root.replacingOccurrences(of: "resolve vpn.example.com:192.0.2.10", with: "resolve vpn.example.com:vpn.example.net"))
        assertRootUnsafe(root.replacingOccurrences(of: "EXAMPLE-COOKIE", with: "EXAMPLE'COOKIE"))
    }

    /// `resolve` is required exactly when `server` names a host, refused for an IP address, and names
    /// `server`'s host: without it the root run would resolve the name again.
    func testResolveMatchesTheServer() throws {
        assertRootUnsafe(root.replacingOccurrences(of: "resolve vpn.example.com:192.0.2.10\n", with: ""))
        assertRootUnsafe(root.replacingOccurrences(of: "resolve vpn.example.com:", with: "resolve vpn.example.net:"))
        assertRootUnsafe(root.replacingOccurrences(of: "resolve vpn.example.com:", with: "resolve vpn:"))
        for host in ["192.0.2.10", "2001:db8::1"] {
            let literal = try OpenConnectConfig(
                host: host, port: 8443, cookie: "webvpn=EXAMPLE-COOKIE", serverCert: examplePin, resolveAddress: nil,
                scriptPath: exampleHook
            ).render()
            XCTAssertNoThrow(try OpenConnectConfig.checkRendered(literal, lineCount: lineCount(literal)))
            assertRootUnsafe(literal.replacingOccurrences(of: "\nscript ", with: "\nresolve \(host):192.0.2.10\nscript "))
            assertRootUnsafe(literal.replacingOccurrences(of: "\nscript ", with: "\nresolve vpn.example.com:192.0.2.10\nscript "))
        }
    }

    /// `server` is parsed by the typed rules: https only, a typed host (lowercase; IPv6 in brackets), a port
    /// without leading zeros and never an explicit 443, and the path the renderer writes.
    func testTheServerURLIsTyped() {
        let server = "server https://vpn.example.com:8443/"
        for bad in [
            "http://vpn.example.com:8443/", "HTTPS://vpn.example.com:8443/", "https:/vpn.example.com:8443/", "https://vpn.example.com:8443",
            "https://alice@vpn.example.com:8443/", "https://vpn.example.com:8443@evil.example/", "https://vpn.example.com:8443/?x=1",
            "https://vpn.example.com:8443/#x", "https://vpn.example.com:8443/engineering", "https://vpn.example.com:8443//",
            "https://vpn.example.com:443/", "https://vpn.example.com:08443/", "https://vpn.example.com:0/", "https://vpn.example.com:65536/",
            "https://vpn.example.com:/", "https://vpn.example.com:84a3/", "https://VPN.example.com:8443/", "https://vpn_example.com:8443/",
            "https://-vpn.example.com:8443/", "https://[vpn.example.com]:8443/", "https://[192.0.2.10]:8443/", "https://2001:db8::1/",
            "https://[2001:db8::1%en0]:8443/", "https://[2001:db8::1]x/", "https://:8443/", "https:///"
        ] {
            assertRootUnsafe(root.replacingOccurrences(of: server, with: "server \(bad)"))
        }
        // The sign-in file's path is a user group by its typed rule.
        for bad in [
            "https://vpn.example.com/../../x", "https://vpn.example.com//x", "https://vpn.example.com/eng/../x",
            "https://vpn.example.com/eng?x=1", "https://vpn.example.com/eng#x", "https://vpn.example.com/eng%2fx",
            "https://vpn.example.com/eng@x", "https://vpn.example.com/eng:x", "https://alice@vpn.example.com/eng",
            "https://vpn.example.com:443/eng", "https://vpn.example.com"
        ] {
            assertAuthUnsafe(auth.replacingOccurrences(of: "server https://vpn.example.com/eng", with: "server \(bad)"))
        }
    }

    func testTheServerURLParser() {
        XCTAssertEqual(OpenConnectSyntax.parseServerURL("https://vpn.example.com/")?.port, 443)
        XCTAssertEqual(OpenConnectSyntax.parseServerURL("https://vpn.example.com:8443/eng/remote")?.path, "eng/remote")
        XCTAssertEqual(OpenConnectSyntax.parseServerURL("https://[2001:db8::1]:8443/")?.host, "2001:db8::1")
        XCTAssertEqual(OpenConnectSyntax.parseServerURL("https://192.0.2.10:1/")?.port, 1)
        XCTAssertEqual(OpenConnectSyntax.parseServerURL("https://vpn.example.com:65535/")?.port, 65535)
        for host in ["vpn.example.com", "VPN.Example.com", "192.0.2.10", "2001:DB8::1"] {
            for port in [443, 8443] {
