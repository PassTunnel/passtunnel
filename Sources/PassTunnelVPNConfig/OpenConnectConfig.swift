import Foundation

/// The openconnect protocols PassTunnel renders files for, by openconnect's names (`protocol`).
public enum OpenConnectProtocol: String, Codable, CaseIterable, Equatable, Sendable {
    /// Cisco AnyConnect.
    case anyconnect
    /// Palo Alto GlobalProtect.
    case gp
}

/// The configuration of the root `openconnect` run that holds a Cisco AnyConnect or Palo Alto GlobalProtect
/// tunnel (`<run>/openconnect.conf`), rendered from typed fields. The root run never signs in: it gets the
/// session cookie the user's own sign-in run returned (`OpenConnectAuthResult`), the server key that run
/// accepted, and the address it connected to.
///
/// openconnect's config file (9.21 `next_option`, main.c 1199–1300) holds one option per line: blanks at
/// the start of a line are skipped, `#` lines are comments, the option name must be followed by a blank or
/// `=`, then blanks and one `=` are skipped and the value is the rest of the line, up to a NUL. There is no
/// quoting, so every value is validated to stay on its own line, to start with neither a blank nor `=`
/// (which would be skipped), to end without a blank, and to hold no control character; the finished text
/// is checked again (`checkRendered`).
public struct OpenConnectConfig: Equatable, CustomStringConvertible, CustomDebugStringConvertible, CustomReflectable {
    public var `protocol`: OpenConnectProtocol
    /// The server the tunnel connects to: a host name, or an IPv4 or IPv6 literal (no brackets, no port, no zone
    /// id). For Cisco AnyConnect the profile's host; for GlobalProtect the gateway the sign-in ended on.
    public var host: String
    public var port: Int
    /// The session cookie from the sign-in run: for Cisco AnyConnect under its name (`OpenConnectCookie`:
    /// `webvpn=…`, or the STRAP form), for GlobalProtect as printed (`GlobalProtectCookie`). A bearer secret: no
    /// description, mirror or error has it.
    public var cookie: String
    /// The key the sign-in run accepted (its `FINGERPRINT`): `pin-sha256:` and the full base64 SHA-256 of
    /// the server's public key. Always set, and the tunnel run's only trust (openconnect turns system trust
    /// off with it), so the tunnel cannot reach another key than the one the credentials went to.
    public var serverCert: String
    /// The address the sign-in run connected to (its `RESOLVE`), rendered as `resolve <host>:<address>` so
    /// DNS cannot move the tunnel between the runs. Required for a host name, nil for an IP-literal host.
    public var resolveAddress: String?
    /// The hook openconnect runs as root (`script`); always rendered, or openconnect would run its
    /// compiled-in vpnc-script.
    public var scriptPath: String
    /// TLS only: renders `no-dtls`. DTLS (for GlobalProtect: ESP) is on by default.
    public var tlsOnly: Bool
    /// Renders `disable-ipv6`: GlobalProtect only, for a Linux openconnect older than 9.20 (which reads a
    /// gateway's IPv6 split includes as excludes). Refused for Cisco AnyConnect.
    public var disableIPv6: Bool

    public enum ValidationError: Error, Equatable, LocalizedError, CustomStringConvertible {
        case invalidHost
        case invalidPort(Int)
        case invalidServerCert
        case invalidValue(field: String, reason: String)
        /// The rendered text failed the final check (`checkRendered`): a validator let something through.
        case unsafeOutput(String)

        public var description: String {
            switch self {
            case .invalidHost: return "Invalid server host name."
            case .invalidPort(let p): return "Invalid port \(p) (must be 1–65535)."
            case .invalidServerCert:
                return "The server certificate must be pin-sha256: followed by the full base64 SHA-256 of its public key (44 characters)."
            case .invalidValue(let f, let r): return "Invalid \(f): \(r)."
            case .unsafeOutput(let r): return "The openconnect configuration failed its final check: \(r)."
            }
        }
        public var errorDescription: String? { description }
    }

    public static let maxHostBytes = 253
    /// The longest `cookie` option accepted (`OpenConnectCookie`).
    public static let maxCookieBytes = 4096
    /// The longest `script` or `cafile` path (macOS `PATH_MAX` is 1,024 with its NUL).
    public static let maxPathBytes = 1023
    /// openconnect's default is 300 seconds (owner decision 12).
    public static let reconnectTimeout = 60
    /// The system's CA bundle on the Mac (root-owned); Linux passes the distribution's bundle it checked.
    public static let systemCAFile = "/etc/ssl/cert.pem"
    /// The first line of both rendered files.
    public static let header = "# Generated by PassTunnel. Do not edit."

    public init(
        protocol: OpenConnectProtocol = .anyconnect, host: String, port: Int = 443, cookie: String, serverCert: String,
        resolveAddress: String?, scriptPath: String, tlsOnly: Bool = false, disableIPv6: Bool = false
    ) {
        self.protocol = `protocol`
        self.host = host
        self.port = port
        self.cookie = cookie
        self.serverCert = serverCert
        self.resolveAddress = resolveAddress
        self.scriptPath = scriptPath
        self.tlsOnly = tlsOnly
        self.disableIPv6 = disableIPv6
    }

    /// The profile's own fields only: the cookie is redacted, and the values the sign-in output supplied
    /// (the accepted key, the resolved address) are shown only as set or not. For GlobalProtect the host and
    /// port are the gateway's, which the portal chose (and could make repeat the cookie), so they are
    /// redacted too.
    public var description: String {
        "OpenConnectConfig(protocol: \(self.protocol.rawValue), host: \(shownHost), port: \(shownPort), cookie: <redacted>, "
            + "serverCert: \(serverCert.isEmpty ? "<none>" : "<set>"), resolveAddress: \(resolveAddress == nil ? "nil" : "<set>"), "
            + "scriptPath: \(scriptPath), tlsOnly: \(tlsOnly), disableIPv6: \(disableIPv6))"
    }
    public var debugDescription: String { description }
    public var customMirror: Mirror {
        Mirror(
            self,
            children: [
                "protocol": self.protocol.rawValue, "host": shownHost, "port": self.protocol == .gp ? "<redacted>" as Any : port,
                "cookie": "<redacted>",
                "serverCert": serverCert.isEmpty ? "<none>" : "<set>", "resolveAddress": resolveAddress == nil ? "nil" : "<set>",
                "scriptPath": scriptPath, "tlsOnly": tlsOnly, "disableIPv6": disableIPv6
            ])
    }

    /// The host and port as descriptions show them: the profile's for Cisco AnyConnect, redacted for
    /// GlobalProtect (the gateway's, the server's choice).
    var shownHost: String { self.protocol == .gp ? "<redacted>" : host }
    var shownPort: String { self.protocol == .gp ? "<redacted>" : String(port) }

    public func validate() throws {
        guard OpenConnectSyntax.isValidHost(host) else { throw ValidationError.invalidHost }
        guard (1...65535).contains(port) else { throw ValidationError.invalidPort(port) }
        switch self.protocol {
        case .anyconnect:
            guard OpenConnectCookie.isValidTunnelOption(cookie) else {
                throw ValidationError.invalidValue(
                    field: "cookie",
                    reason: "not the webvpn cookie under its name, nor openconnect's STRAP form, within \(Self.maxCookieBytes) bytes")
            }
            guard !disableIPv6 else { throw ValidationError.invalidValue(field: "disable-ipv6", reason: Self.globalProtectOnly) }
        case .gp:
            guard GlobalProtectCookie.isValidTunnelOption(cookie) else {
                throw ValidationError.invalidValue(
                    field: "cookie", reason: "not openconnect's GlobalProtect cookie, within \(Self.maxCookieBytes) bytes")
            }
        }
        guard OpenConnectPin.isValid(serverCert) else { throw ValidationError.invalidServerCert }
        if OpenConnectSyntax.isIPLiteral(host) {
            // openconnect splits `resolve` at its first ':' and connects to the literal anyway.
            guard resolveAddress == nil else {
                throw ValidationError.invalidValue(field: "resolve address", reason: "not used for a server given as an IP address")
            }
        } else {
            guard let resolveAddress, OpenConnectSyntax.isIPLiteral(resolveAddress) else {
                throw ValidationError.invalidValue(field: "resolve address", reason: "not an IPv4 or IPv6 address")
            }
        }
        guard OpenConnectSyntax.isSafePath(scriptPath) else {
            throw ValidationError.invalidValue(
                field: "script", reason: "not an absolute path of letters, digits and / . _ - without empty, . or .. components")
        }
    }

    static let globalProtectOnly = "used only for Palo Alto GlobalProtect"

    /// Every key `render` can write, in its order (`disable-ipv6` only for GlobalProtect).
    public static let renderedKeys = [
        "protocol", "server", "cookie", "servercert", "resolve", "script", "non-inter", "reconnect-timeout", "no-dtls",
        "disable-ipv6"
    ]

    /// The config file text. Throws `ValidationError` instead of emitting anything unsafe: the fields are
    /// validated first, and the finished text is checked again (`checkRendered`) before it is returned.
    public func render() throws -> String {
        try validate()
        var lines = [
            Self.header,
            "protocol \(self.protocol.rawValue)",
            // The checked host and port, never the server's text; neither protocol's tunnel has a path.
            "server \(OpenConnectSyntax.serverURL(host: host, port: port, usergroup: ""))",
            "cookie \(cookie)",
            "servercert \(serverCert)"
        ]
        // The same lowercased host as in `server`: openconnect compares the two byte for byte.
        if let resolveAddress { lines.append("resolve \(host.lowercased()):\(resolveAddress)") }
        lines.append("script \(scriptPath)")
        lines.append("non-inter")
        lines.append("reconnect-timeout \(Self.reconnectTimeout)")
        if tlsOnly { lines.append("no-dtls") }
        if disableIPv6 { lines.append("disable-ipv6") }
        let text = lines.joined(separator: "\n") + "\n"
        try Self.checkRendered(text, lineCount: lines.count)
        return text
    }

    /// Defense in depth for the file root's openconnect reads: `text` must be the header and then exactly
    /// `lineCount - 1` option lines, each ending in "\n", with no NUL, CR or other control byte. Each line is
    /// a key from `renderedKeys` (each at most once, in that order, the required ones all present) followed
    /// by one space and a value openconnect reads back unchanged, or a key without a value alone; `protocol`,
    /// `servercert`, `resolve`, `script` and `reconnect-timeout` must also hold what `render` writes. `protocol`
    /// is `anyconnect` or `gp`, and the rest is checked by that protocol's rules: the cookie's shape
    /// (`OpenConnectCookie` or `GlobalProtectCookie`), and `disable-ipv6` only for GlobalProtect.
    public static func checkRendered(_ text: String, lineCount: Int) throws {
        let gp = OpenConnectSyntax.protocolLine(text) == .gp
        var specs: [OpenConnectSyntax.Spec] = [
            .init("protocol", required: true) { $0 == (gp ? OpenConnectProtocol.gp : .anyconnect).rawValue },
            // The tunnel run connects without a path (AnyConnect's user group is the sign-in's only).
            .init("server", required: true) { OpenConnectSyntax.parseServerURL($0)?.path == "" },
            .init("cookie", required: true, value: gp ? GlobalProtectCookie.isValidTunnelOption : OpenConnectCookie.isValidTunnelOption),
            .init("servercert", required: true, value: OpenConnectPin.isValid),
            .init("resolve", required: false, value: OpenConnectSyntax.isValidResolveOption),
            .init("script", required: true, value: OpenConnectSyntax.isSafePath),
            .init("non-inter", required: true, value: nil),
            .init("reconnect-timeout", required: true) { $0 == String(reconnectTimeout) },
            .init("no-dtls", required: false, value: nil)
        ]
        if gp { specs.append(.init("disable-ipv6", required: false, value: nil)) }
        let options = try OpenConnectSyntax.check(text, lineCount: lineCount, specs: specs)
        // `resolve` is there exactly when `server` names a host (without it the root run would resolve the
        // name again), and names that host: openconnect compares the two byte for byte.
        guard let server = options.first(where: { $0.key == "server" })?.value, let url = OpenConnectSyntax.parseServerURL(server) else {
            throw ValidationError.unsafeOutput("no server")
        }
        let resolve = options.first(where: { $0.key == "resolve" })?.value
        if OpenConnectSyntax.isIPLiteral(url.host) {
            guard resolve == nil else { throw ValidationError.unsafeOutput("resolve for a server given as an IP address") }
        } else {
            guard let resolve else { throw ValidationError.unsafeOutput("no resolve for a server given as a host name") }
            guard OpenConnectSyntax.resolveName(resolve) == url.host else {
                throw ValidationError.unsafeOutput("resolve names another host than server")
            }
        }
    }
}

/// The configuration of the user's own `openconnect --authenticate` run (the sign-in), rendered from typed
/// fields like `OpenConnectConfig`. It carries no secret: the password and the code go on standard input
/// (`OpenConnectAnswers`). The user name is here and never in argv, which every local user can read.
public struct OpenConnectAuthConfig: Equatable, Sendable {
    public var `protocol`: OpenConnectProtocol
    /// The profile's host (for GlobalProtect the portal's, or with `skipPortal` the gateway's).
    public var host: String
    public var port: Int
    /// Cisco AnyConnect: the URL path of the sign-in (`https://host/usergroup`): empty, or letters, digits and
    /// `- _ . ~ /`. Empty for GlobalProtect, whose path is `skipPortal`'s.
    public var usergroup: String
    public var username: String
    /// Cisco AnyConnect: matched against the server's group list: empty, or 1–255 bytes. Empty for
    /// GlobalProtect, whose `authgroup` line is `gateway`.
    public var authgroup: String
    /// The profile's pin (`pin-sha256:` …), or empty to verify the server with the system CA bundle. For
    /// GlobalProtect the portal's key (or, with `skipPortal`, the only server's).
    public var serverCert: String
    /// GlobalProtect: sign in to `host` as a gateway (the URL path `gateway`), without the portal. False for
    /// Cisco AnyConnect.
    public var skipPortal: Bool
    /// GlobalProtect: the gateway's label as the portal lists it, by `authgroup`'s rule, rendered as
    /// `authgroup`; empty to take the portal's only gateway. Empty for Cisco AnyConnect.
    public var gateway: String
    /// GlobalProtect: the gateway's pin when its key is not the portal's, or empty. Empty for Cisco AnyConnect.
    public var gatewayServerCert: String

    public static let maxUsergroupBytes = 255
    public static let maxAuthgroupBytes = 255
    public static let maxGatewayBytes = 255
    public static let maxUsernameBytes = 255
    /// The URL path that signs in to a GlobalProtect gateway without its portal.
    public static let gatewayPath = "gateway"

    // The rules for a Cisco AnyConnect profile's fields, as `validate` applies them, for PassTunnelKit
    // (`ProfileFields`, `Profile.checkAnyConnectFields`) and the URL a user pastes (`AnyConnectServer`).

    /// A host name or an IPv4 or IPv6 literal (no brackets, port or zone id), at most 253 bytes.
    public static func isValidHost(_ s: String) -> Bool { OpenConnectSyntax.isValidHost(s) }

    /// An IPv6 literal without brackets or zone id.
    public static func isIPv6Literal(_ s: String) -> Bool { OpenConnectSyntax.isIPv6Literal(s) }

    /// A non-empty user group: 1–255 bytes of letters, digits and `- _ . ~ /`, without `..` or a leading `/`.
    public static func isValidUsergroup(_ s: String) -> Bool { OpenConnectSyntax.isValidUsergroup(s) }

    /// A non-empty group name: 1–255 bytes, no control character or line separator, no surrounding
    /// whitespace, no leading `=`.
    public static func isValidAuthgroup(_ s: String) -> Bool { OpenConnectSyntax.isValidText(s, maxBytes: maxAuthgroupBytes) }

    /// A non-empty GlobalProtect gateway label, by the group name's rule.
    public static func isValidGateway(_ s: String) -> Bool { OpenConnectSyntax.isValidText(s, maxBytes: maxGatewayBytes) }

    /// A non-empty user name, by the same rule as a group name.
    public static func isValidUsername(_ s: String) -> Bool { OpenConnectSyntax.isValidText(s, maxBytes: maxUsernameBytes) }

    public init(
        protocol: OpenConnectProtocol = .anyconnect, host: String, port: Int = 443, usergroup: String = "", username: String,
        authgroup: String = "", serverCert: String = "", skipPortal: Bool = false, gateway: String = "", gatewayServerCert: String = ""
    ) {
        self.protocol = `protocol`
        self.host = host
        self.port = port
        self.usergroup = usergroup
        self.username = username
        self.authgroup = authgroup
        self.serverCert = serverCert
        self.skipPortal = skipPortal
        self.gateway = gateway
        self.gatewayServerCert = gatewayServerCert
    }

    public func validate() throws {
        typealias E = OpenConnectConfig.ValidationError
        guard OpenConnectSyntax.isValidHost(host) else { throw E.invalidHost }
        guard (1...65535).contains(port) else { throw E.invalidPort(port) }
        switch self.protocol {
        case .anyconnect:
            guard usergroup.isEmpty || OpenConnectSyntax.isValidUsergroup(usergroup) else {
                throw E.invalidValue(
                    field: "user group",
                    reason: "not 1–\(Self.maxUsergroupBytes) bytes of letters, digits and - _ . ~ / without .. or a leading /")
            }
            guard !skipPortal else { throw E.invalidValue(field: "skip portal", reason: OpenConnectConfig.globalProtectOnly) }
            guard gateway.isEmpty else { throw E.invalidValue(field: "gateway", reason: OpenConnectConfig.globalProtectOnly) }
            guard gatewayServerCert.isEmpty else {
                throw E.invalidValue(field: "gateway server certificate", reason: OpenConnectConfig.globalProtectOnly)
            }
        case .gp:
            // The path decides portal or gateway, and could name a field for a single sign-on cookie.
            guard usergroup.isEmpty else { throw E.invalidValue(field: "user group", reason: "not used for Palo Alto GlobalProtect") }
            guard authgroup.isEmpty else { throw E.invalidValue(field: "group", reason: "not used for Palo Alto GlobalProtect") }
        }
        try OpenConnectSyntax.checkText(username, field: "user name", maxBytes: Self.maxUsernameBytes, allowEmpty: false)
        try OpenConnectSyntax.checkText(authgroup, field: "group", maxBytes: Self.maxAuthgroupBytes, allowEmpty: true)
        try OpenConnectSyntax.checkText(gateway, field: "gateway", maxBytes: Self.maxGatewayBytes, allowEmpty: true)
        guard serverCert.isEmpty || OpenConnectPin.isValid(serverCert) else { throw E.invalidServerCert }
        guard gatewayServerCert.isEmpty || OpenConnectPin.isValid(gatewayServerCert) else { throw E.invalidServerCert }
    }

    /// Every key `render` can write, in its order (`servercert` twice and `disable-ipv6` only for
    /// GlobalProtect).
    public static let renderedKeys = [
        "protocol", "server", "user", "authgroup", "servercert", "no-system-trust", "cafile", "non-inter", "passwd-on-stdin",
        "no-external-auth", "disable-ipv6"
    ]

    /// The config file text, checked again before it is returned (`checkRendered`). With a pin it is the only
    /// trust (`servercert`); without one, `no-system-trust` and `cafile caFile`, never GnuTLS's compiled-in
    /// store. `caFile` is the Mac's system bundle, or the distribution's that the Linux daemon checked.
    /// `noExternalAuth` renders `no-external-auth` (openconnect 9.10 and later; the caller knows whether the
    /// installed openconnect has it: the Mac's bundled 9.21 does, older Linux versions do not).
    ///
    /// For GlobalProtect: the path is empty (the portal, or the gateway when the server is none) or `gateway`
    /// (`skipPortal`), `gateway` is the `authgroup` line, and each pin that is set (`serverCert`, then
    /// `gatewayServerCert`) is a `servercert` line, since openconnect checks every server of the run against
    /// them and any of them turns system trust off. `disableIPv6` renders `disable-ipv6` (GlobalProtect only,
    /// for a Linux openconnect older than 9.20).
    public func render(caFile: String = OpenConnectConfig.systemCAFile, noExternalAuth: Bool, disableIPv6: Bool = false) throws -> String {
        try validate()
        guard OpenConnectSyntax.isSafePath(caFile) else {
            throw OpenConnectConfig.ValidationError.invalidValue(
                field: "CA file", reason: "not an absolute path of letters, digits and / . _ - without empty, . or .. components")
        }
        let gp = self.protocol == .gp
        guard gp || !disableIPv6 else {
            throw OpenConnectConfig.ValidationError.invalidValue(field: "disable-ipv6", reason: OpenConnectConfig.globalProtectOnly)
        }
        let path = gp ? (skipPortal ? Self.gatewayPath : "") : usergroup
        var lines = [
            OpenConnectConfig.header,
            "protocol \(self.protocol.rawValue)",
            "server \(OpenConnectSyntax.serverURL(host: host, port: port, usergroup: path))",
            "user \(username)"
        ]
        let group = gp ? gateway : authgroup
        if !group.isEmpty { lines.append("authgroup \(group)") }
        let pins = [serverCert, gatewayServerCert].filter { !$0.isEmpty }
        if pins.isEmpty {
            lines.append("no-system-trust")
            lines.append("cafile \(caFile)")
        } else {
            lines += pins.map { "servercert \($0)" }
        }
        lines.append("non-inter")
        lines.append("passwd-on-stdin")
        if noExternalAuth { lines.append("no-external-auth") }
        if disableIPv6 { lines.append("disable-ipv6") }
        let text = lines.joined(separator: "\n") + "\n"
        try Self.checkRendered(text, lineCount: lines.count, caFile: caFile)
        return text
    }

    /// As `OpenConnectConfig.checkRendered`, for this file's keys: also the trust is exactly `servercert`
    /// with a valid pin, or both `no-system-trust` and `cafile caFile`. `protocol` is `anyconnect` or `gp`, and
    /// the rest is checked by that protocol's rules: for GlobalProtect the path is empty or `gateway`,
    /// `servercert` may appear twice (once in every other file) and `disable-ipv6` may follow.
    public static func checkRendered(_ text: String, lineCount: Int, caFile: String) throws {
        let gp = OpenConnectSyntax.protocolLine(text) == .gp
        var specs: [OpenConnectSyntax.Spec] = [
            .init("protocol", required: true) { $0 == (gp ? OpenConnectProtocol.gp : .anyconnect).rawValue },
            .init("server", required: true) { value in
                guard let url = OpenConnectSyntax.parseServerURL(value) else { return false }
                // No user group and no `:<field>` for a single sign-on cookie.
                return !gp || url.path.isEmpty || url.path == gatewayPath
            },
            .init("user", required: true) { OpenConnectSyntax.isValidText($0, maxBytes: maxUsernameBytes) },
            .init("authgroup", required: false) { OpenConnectSyntax.isValidText($0, maxBytes: gp ? maxGatewayBytes : maxAuthgroupBytes) },
            .init("servercert", required: false, value: OpenConnectPin.isValid)
        ]
        if gp { specs.append(.init("servercert", required: false, value: OpenConnectPin.isValid)) }
        specs += [
            .init("no-system-trust", required: false, value: nil),
            .init("cafile", required: false) { $0 == caFile && OpenConnectSyntax.isSafePath($0) },
            .init("non-inter", required: true, value: nil),
            .init("passwd-on-stdin", required: true, value: nil),
            .init("no-external-auth", required: false, value: nil)
        ]
        if gp { specs.append(.init("disable-ipv6", required: false, value: nil)) }
        let keys = try OpenConnectSyntax.check(text, lineCount: lineCount, specs: specs).map(\.key)
        let pinned = keys.contains("servercert")
        let systemCAs = keys.contains("no-system-trust") && keys.contains("cafile")
        let partial = keys.contains("no-system-trust") != keys.contains("cafile")
        guard pinned != systemCAs, !partial else {
            throw OpenConnectConfig.ValidationError.unsafeOutput("the trust is not a pin or the system CA bundle alone")
        }
    }
}

/// openconnect's `servercert` pin, in the only form PassTunnel accepts: `pin-sha256:` followed by the full
/// base64 SHA-256 of the server's public key (SubjectPublicKeyInfo), 43 characters and `=`. openconnect
/// itself would also match a prefix of 4 characters or more, a `sha256:` or `sha1:` hex digest, or a bare
/// SHA-1 of the whole certificate (`library.c` 1694–1745); all of them are refused.
public enum OpenConnectPin {
    public static let prefix = "pin-sha256:"
    /// `prefix` and 44 base64 characters.
    public static let length = 55

    /// The stored form, exactly: the lowercase prefix, 43 base64 characters of which the last encodes the
    /// hash's final 4 bits (so its low 2 bits are 0, as openconnect prints it), and `=`.
    public static func isValid(_ s: String) -> Bool {
        let bytes = Array(s.utf8)
        guard bytes.count == length, bytes.starts(with: prefix.utf8) else { return false }
        let digest = bytes[prefix.utf8.count...]
        guard digest.last == UInt8(ascii: "="), let lastIndex = base64Value(digest[digest.endIndex - 2]) else { return false }
        return lastIndex % 4 == 0 && digest.dropLast().allSatisfy { base64Value($0) != nil }
    }

    /// A pin the user typed or pasted, in the stored form: surrounding blanks and line breaks removed and the
    /// prefix lowercased. Nil for anything that is not a full `pin-sha256:` pin.
    public static func normalize(_ s: String) -> String? {
        var bytes = Array(s.utf8)
        func isBlank(_ b: UInt8) -> Bool { b == 0x20 || (0x09...0x0D).contains(b) }
        while let f = bytes.first, isBlank(f) { bytes.removeFirst() }
        while let l = bytes.last, isBlank(l) { bytes.removeLast() }
        let p = Array(prefix.utf8)
        guard bytes.count == length, bytes[..<p.count].map({ asciiLowercase($0) }) == p else { return nil }
        let normalized = String(decoding: p + bytes[p.count...], as: UTF8.self)
        return isValid(normalized) ? normalized : nil
    }

    static func asciiLowercase(_ b: UInt8) -> UInt8 { (65...90).contains(b) ? b + 32 : b }

    static func base64Value(_ b: UInt8) -> Int? {
        switch b {
        case UInt8(ascii: "A")...UInt8(ascii: "Z"): return Int(b - UInt8(ascii: "A"))
        case UInt8(ascii: "a")...UInt8(ascii: "z"): return Int(b - UInt8(ascii: "a")) + 26
        case UInt8(ascii: "0")...UInt8(ascii: "9"): return Int(b - UInt8(ascii: "0")) + 52
        case UInt8(ascii: "+"): return 62
        case UInt8(ascii: "/"): return 63
        default: return nil
        }
    }
}

/// The rules shared by the openconnect files and the sign-in result.
enum OpenConnectSyntax {
    // MARK: Hosts and URLs

    /// `FortiConfig.isValidHost` without an IPv6 zone id: a URL cannot carry one the way openconnect reads it.
    static func isValidHost(_ s: String) -> Bool {
        s.utf8.count <= OpenConnectConfig.maxHostBytes && !s.utf8.contains(UInt8(ascii: "%")) && FortiConfig.isValidHost(s)
    }

    static func isIPv4Literal(_ s: String) -> Bool { ipv4Bytes(s) != nil }

    /// An IPv6 literal without brackets or zone id.
    static func isIPv6Literal(_ s: String) -> Bool {
        s.utf8.count <= 45 && !s.utf8.contains(UInt8(ascii: "%")) && FortiConfig.isValidIPv6(s)
    }

    static func isIPLiteral(_ s: String) -> Bool { isIPv4Literal(s) || isIPv6Literal(s) }

    static func ipv4Bytes(_ s: String) -> [UInt8]? {
        guard (7...15).contains(s.utf8.count), s.utf8.allSatisfy({ FortiConfig.isASCIIDigit($0) || $0 == UInt8(ascii: ".") }) else {
            return nil
        }
        var addr = in_addr()
        guard s.withCString({ inet_pton(AF_INET, $0, &addr) }) == 1 else { return nil }
        return withUnsafeBytes(of: &addr) { Array($0) }
    }

    /// The address's bytes, for comparing two spellings of one IPv6 address.
    static func ipBytes(_ s: String) -> [UInt8]? {
        if let v4 = ipv4Bytes(s) { return v4 }
        guard isIPv6Literal(s) else { return nil }
        var addr = in6_addr()
        guard s.withCString({ inet_pton(AF_INET6, $0, &addr) }) == 1 else { return nil }
        return withUnsafeBytes(of: &addr) { Array($0) }
    }

    /// The host as a URL writes it: lowercased (ASCII only, already checked), an IPv6 literal in brackets.
    static func urlHost(_ host: String) -> String {
        let lower = host.lowercased()
        return isIPv6Literal(host) ? "[\(lower)]" : lower
    }

    /// `https://<host>[:<port>]/<usergroup>`, the port left out when it is 443, as openconnect prints
    /// `CONNECT_URL` (`library.c` 953–980).
    static func serverURL(host: String, port: Int, usergroup: String) -> String {
        "https://\(urlHost(host))\(port == 443 ? "" : ":\(port)")/\(usergroup)"
    }

    /// A server URL exactly as `serverURL` writes it, split into its parts: `https://`, a host by the
    /// typed rule (lowercase; an IPv6 literal in brackets, an IPv4 literal or a host name), an optional
    /// `:port` (1–65535, digits without a leading zero, never 443, which is left out), `/`, and a path that
    /// is empty or a user group by its typed rule. No user info, query or fragment can pass: none of `@`,
    /// `?`, `#` is allowed in any part. Nil for anything else.
    static func parseServerURL(_ s: String) -> (host: String, port: Int, path: String)? {
        let scheme = "https://"
        guard s.hasPrefix(scheme) else { return nil }
        let rest = s.dropFirst(scheme.count)
        guard let slash = rest.firstIndex(of: "/") else { return nil }
        let authority = rest[..<slash]
        let path = String(rest[rest.index(after: slash)...])
        var host: Substring
        var portText: Substring?
        if authority.hasPrefix("[") {
            guard let close = authority.firstIndex(of: "]") else { return nil }
            host = authority[authority.index(after: authority.startIndex)..<close]
            let after = authority[authority.index(after: close)...]
            if !after.isEmpty {
                guard after.hasPrefix(":") else { return nil }
                portText = after.dropFirst()
            }
            guard isIPv6Literal(String(host)) else { return nil }
        } else {
            let parts = authority.split(separator: ":", maxSplits: 1, omittingEmptySubsequences: false)
            host = parts[0]
            if parts.count == 2 { portText = parts[1] }
            guard !host.contains(":"), isValidHost(String(host)) else { return nil }
        }
        guard host == host.lowercased() else { return nil }
        var port = 443
        if let portText {
            guard let first = portText.first, first != "0", portText.count <= 5, portText.utf8.allSatisfy(FortiConfig.isASCIIDigit),
                let p = Int(portText), (1...65535).contains(p), p != 443
            else { return nil }
            port = p
        }
        guard path.isEmpty || isValidUsergroup(path) else { return nil }
        return (String(host), port, path)
    }

    static func isValidUsergroup(_ s: String) -> Bool {
        (1...OpenConnectAuthConfig.maxUsergroupBytes).contains(s.utf8.count) && !s.hasPrefix("/") && !s.contains("..")
            && s.utf8.allSatisfy { FortiConfig.isASCIIAlphanumeric($0) || "-_.~/".utf8.contains($0) }
    }

    /// A `resolve` value as `render` writes it: `<host name>:<IP literal>` (a host name has no ':', so
    /// openconnect's split at the first ':' finds this one).
    static func isValidResolveOption(_ s: String) -> Bool {
        guard let colon = s.firstIndex(of: ":") else { return false }
        let name = String(s[..<colon]), address = String(s[s.index(after: colon)...])
        return isValidHost(name) && !isIPLiteral(name) && name == name.lowercased() && isIPLiteral(address)
    }

    /// `resolve`'s host name (before the first ':').
    static func resolveName(_ s: String) -> Substring { s.prefix { $0 != ":" } }

    // MARK: Values

    /// An absolute path of `A–Z a–z 0–9 / . _ -` only (openconnect passes `script` to `/bin/sh -c`), at most
    /// `maxPathBytes`, every component non-empty and neither `.` nor `..`.
    static func isSafePath(_ s: String) -> Bool {
        guard s.hasPrefix("/"), s.utf8.count <= OpenConnectConfig.maxPathBytes,
            s.utf8.allSatisfy({ FortiConfig.isASCIIAlphanumeric($0) || "/._-".utf8.contains($0) })
        else { return false }
        return s.split(separator: "/", omittingEmptySubsequences: false).dropFirst().allSatisfy { !$0.isEmpty && $0 != "." && $0 != ".." }
    }

    /// A free-text value (user name, group): at most `maxBytes` bytes, no control character or Unicode line
    /// separator, not starting or ending with whitespace, not starting with `=` (openconnect skips one).
    static func checkText(_ s: String, field: String, maxBytes: Int, allowEmpty: Bool) throws {
        typealias E = OpenConnectConfig.ValidationError
        if s.isEmpty {
            if allowEmpty { return }
            throw E.invalidValue(field: field, reason: "must not be empty")
        }
        guard s.utf8.count <= maxBytes else { throw E.invalidValue(field: field, reason: "longer than \(maxBytes) bytes") }
        guard !s.unicodeScalars.contains(where: FortiConfig.isForbiddenScalar) else {
            throw E.invalidValue(field: field, reason: "contains a line break or control character")
        }
        if let f = s.unicodeScalars.first, let l = s.unicodeScalars.last, f.properties.isWhitespace || l.properties.isWhitespace {
            throw E.invalidValue(field: field, reason: "cannot start or end with whitespace")
        }
        guard !s.hasPrefix("=") else { throw E.invalidValue(field: field, reason: "cannot start with =") }
    }

    static func isValidText(_ s: String, maxBytes: Int) -> Bool {
        (try? checkText(s, field: "", maxBytes: maxBytes, allowEmpty: false)) != nil
    }

    // MARK: The final check

    /// The protocol a rendered file's second line (after the header) names exactly (`protocol <name>`), which
    /// decides the rules the rest of the file is checked by; nil for anything else (which then fails the
    /// Cisco AnyConnect rules, whose first option is `protocol anyconnect`).
    static func protocolLine(_ text: String) -> OpenConnectProtocol? {
        let lines = text.utf8.split(separator: 0x0A, maxSplits: 2, omittingEmptySubsequences: false)
        guard lines.count > 1 else { return nil }
        let line = String(decoding: lines[1], as: UTF8.self)
        guard line.hasPrefix("protocol ") else { return nil }
        return OpenConnectProtocol(rawValue: String(line.dropFirst("protocol ".count)))
    }

    struct Spec {
        let key: String
        let required: Bool
        /// Nil for an option without a value.
        let value: ((String) -> Bool)?
        init(_ key: String, required: Bool, value: ((String) -> Bool)?) {
            self.key = key
            self.required = required
            self.value = value
        }
    }

    /// Checks `text` as described at `OpenConnectConfig.checkRendered` and returns the options it found, in
    /// order, with their values (nil for an option without one).
    static func check(_ text: String, lineCount: Int, specs: [Spec]) throws -> [(key: String, value: String?)] {
        func fail(_ reason: String) -> OpenConnectConfig.ValidationError { .unsafeOutput(reason) }
        let bytes = Array(text.utf8)
        guard !bytes.contains(0) else { throw fail("NUL byte") }
        guard !bytes.contains(0x0D) else { throw fail("carriage return") }
        guard !bytes.contains(where: { ($0 < 0x20 && $0 != 0x0A) || $0 == 0x7F }) else { throw fail("control byte") }
        guard bytes.last == 0x0A else { throw fail("no final line break") }
        let lines = bytes.dropLast().split(separator: 0x0A, omittingEmptySubsequences: false)
        guard lines.count == lineCount else { throw fail("\(lines.count) lines instead of \(lineCount)") }
        guard let first = lines.first, Array(first) == Array(OpenConnectConfig.header.utf8) else { throw fail("no header line") }
        var next = 0  // index into specs: keys appear once each, in order
        var found: [(key: String, value: String?)] = []
        for (n, line) in lines.enumerated().dropFirst() {
            let space = line.firstIndex(of: 0x20)
            let key = String(decoding: line[..<(space ?? line.endIndex)], as: UTF8.self)
            guard let k = specs[next...].firstIndex(where: { $0.key == key }) else {
                throw fail("line \(n + 1) has an unexpected or repeated option")
            }
            next = k + 1
            if let valueCheck = specs[k].value {
                guard let space else { throw fail("line \(n + 1) has no value") }
                let value = line[(space + 1)...]
                // openconnect skips blanks and one '=' before the value and keeps trailing blanks.
                guard let f = value.first, f != 0x20, f != 0x09, f != UInt8(ascii: "="), value.last != 0x20, value.last != 0x09
                else { throw fail("line \(n + 1) has a value openconnect would read differently") }
                let text = String(decoding: value, as: UTF8.self)
                guard valueCheck(text) else { throw fail("line \(n + 1) has an invalid value") }
                found.append((key, text))
            } else {
                guard space == nil else { throw fail("line \(n + 1) has a value for an option that takes none") }
                found.append((key, nil))
            }
        }
        for spec in specs where spec.required && !found.contains(where: { $0.key == spec.key }) {
            throw fail("the option \(spec.key) is missing")
        }
        return found
    }
}

extension FortiConfig {
    static func isASCIIDigit(_ b: UInt8) -> Bool { (UInt8(ascii: "0")...UInt8(ascii: "9")).contains(b) }
}
